def gen_text(n_sent, pos_p, neg_p):
    sents = []
    for _ in range(n_sent):
        r = rng.random()
        if r < pos_p:
            sents.append(POS_SENTS[rng.integers(len(POS_SENTS))])
        elif r < pos_p + neg_p:
            sents.append(NEG_SENTS[rng.integers(len(NEG_SENTS))])
        else:
            sents.append(NEU_SENTS[rng.integers(len(NEU_SENTS))])
    return "".join(sents)


rows = []
for i in range(N_FIRM):
    code = f"{600000 + i * 10:06d}"
    name = f"模拟公司{i + 1:03d}"
    theta = rng.normal(0, 1)          # 企业潜在语调倾向
    size0 = rng.normal(22.0, 1.2)     # ln(总资产)
    lev0 = np.clip(rng.normal(0.45, 0.15), 0.05, 0.9)
    for t, year in enumerate(YEARS):
        shock = rng.normal(0, 0.6)
        pos_p = 1 / (1 + np.exp(-(0.8 * theta + 1.2 * shock)))
        neg_p = max(0.05, 0.35 - 0.5 * pos_p)
        text = gen_text(int(rng.poisson(22)) + 10, pos_p, neg_p)

        size = size0 + 0.05 * t + rng.normal(0, 0.05)
        lev = np.clip(lev0 + rng.normal(0, 0.03), 0.03, 0.92)
        growth = rng.normal(0.10, 0.25)
        roa_next = 0.035 + 0.018 * (theta + shock) \
                   - 0.008 * (size - 22) - 0.02 * (lev - 0.45) \
                   + 0.005 * growth + rng.normal(0, 0.012)

        rows.append({
            "股票代码": code, "公司简称": name, "年份": year,
            "MD&A文本": text,
            "总资产对数": round(size, 4),
            "资产负债率": round(lev, 4),
            "营业收入增长率": round(growth, 4),
            "下一年度ROA": round(roa_next, 5),
        })

df = pd.DataFrame(rows)
df.to_csv("data/raw_corpus.csv", index=False, encoding="utf-8-sig")
